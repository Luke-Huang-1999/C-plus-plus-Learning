#include<iostream>
#include<string>

using namespace std;

class BankAccount
{
    //宣告變數，private區，不要讓使用者直接修改。
private:
    string id;                  //帳戶編號
    string name;                //持有人姓名
    double balance;             //帳戶餘額
public:
    BankAccount (string i, string n, double b)//建構子宣告，並加函數參數透過傳值的方式，賦值給private區的內部成員
    {
        id = i;
        name = n;
        balance = b;
    }
    void deposit(double money)//宣告函數deposit()，更改balance
    {
        balance += money;
    }

    void withdraw(double money)//宣告withdraw()，檢查餘額並判斷是否提款
    {
        if (balance < money)
        {
            cout << "餘額不足\n";
        }
        else
        {
            balance -= money;
            cout << "提款" << money << "元, 帳戶餘額" << balance << "元\n";
        }
    }

    void show()//輸出目前帳戶資料
    {
        cout << "\n**** 帳戶資料 ****\n";
        cout << "帳戶編號 " << id << "\n"
            << "持有人姓名 " << name << "\n"
            << "目前餘額 " << balance << "\n";
    }
};

int main()
{
    //0.初始化帳戶，這裡建立了一個物件account，呼叫建構子，這三個參數分別賦值給account物件的內部成員，資料存入堆疊區
    BankAccount account("A001", "Luke", 10000);

    //1.顯示目前帳戶資料
    account.show();

    //2. 存入 3000 元；尋找物件accoount中的函數deposit(double money)，並修改balance，結果變成(原有餘額 - 3000)元
    account.deposit(3000);

    //3.顯示目前帳戶資料
    account.show();
    
    //4. 提領 5000 元
    account.withdraw(5000);

    //5.顯示目前帳戶資料
    account.show();

    //6. 嘗試提領 10000 元
    account.withdraw(10000);

    //7.顯示目前帳戶資料
    account.show();

	return 0;
}

